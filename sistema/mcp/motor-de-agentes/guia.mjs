// Por que: la guia (recurso) y el prompt de arranque. Le explican a Claude como esta armado un
// agente para que edite sin romperlo y sin publicar a escondidas.
const GUIA = [
  '# Guia: agentes de agent-master en el hub heyyou',
  '',
  'Un agente contesta leads por WhatsApp o correo. Todo su comportamiento es configuracion del hub:',
  '- settings: model (proveedor:modelo), temperature, persona (como habla), rules (lo que nunca hace), debounceS, budgetCap.',
  '  Proveedores: openai, anthropic, google, openrouter (una llave para todos: openrouter:<marca>/<modelo>, p. ej.',
  '  openrouter:anthropic/claude-sonnet-4.5; usa el nombre exacto de openrouter.ai/models), openai-compatible.',
  '- phases: etapas de la conversacion EN ORDEN (calificador, asesor, cierre...). Cada una tiene objective, promptBlock,',
  '  maxSteps, firstStepToolChoice (auto | required | none), tools (del catalogo: listar_herramientas) y mcpServers',
  '  (servidores de la cuenta con toolAllowList y requiredTools).',
  '- phases[].autoActions: reglas que agent-master cumple SOLO, sin que el modelo decida (una instruccion en el prompt',
  '  el modelo la sigue a veces). [{ id, when: { scratchpad: [claves] }, tool, args, once: true }]: cuando todas las claves',
  '  tienen valor, corre la herramienta (del catalogo) con esos args, una vez por conversacion. Ej.: mover al lead a',
  '  "Calificado" con move_pipeline_stage cuando hay necesidad, presupuesto y fecha_entrega.',
  '- transitions: como se mueve entre fases (fromPhase -> toPhase, kind advance | back | jump, requires = condiciones).',
  '- Fases PRINCIPALES (mode main, la secuencia): la conversacion esta siempre en una sola.',
  '- Fases PARALELAS (mode parallel): activas JUNTO a la principal, y pueden ser varias a la vez (seguimientos, objeciones,',
  '  soporte...). Cada una lleva parallel: triggers (model | keyword con patterns | inactivity con afterMinutes | event),',
  '  fromPhases (vacio = cualquiera), exitOn (reply | model | done | maxAttempts + maxAttempts), resume (main o una fase',
  '  principal) y priority. Ninguna transicion entra a una paralela y no tienen back; si pueden saltar (jump) a una principal.',
  '- send_resource (phases[].tools): envía un archivo de la cuenta por su title (ver listar_recursos). Solo WhatsApp Cloud.',
  '- bindings: que numero (channel whatsapp + channelRef) o buzon atiende. testOnly + testAllowList = solo numeros de prueba.',
  '  Antes de agregar o cambiar un binding usa ver_canales: un canal debe ser de la cuenta en heychat y lo debe contestar uno solo.',
  '- extras: qualification (preguntas y reglas), decisionArgs (argumentos, promociones, garantias), followupRules',
  '  (seguimientos con horario), messageTemplates (plantillas aprobadas de Meta para fuera de 24 h: SOLO las de',
  '  listar_plantillas_whatsapp con usable true; copia name, language y body exactos), companyInfo,',
  '  payment, calendar y productSource (hub, http o db).',
  '- productSource hub (o null): el inventario del hub. http o db: el catalogo del cliente, con connection (nombre de',
  '  guardar_conexion: tipo http para un API, postgres/mysql/mariadb para una base). config:',
  '  http: { search: {method, url, query, responsePath}, get: {method, url, responsePath}, fields, currency }. search usa',
  '    {q} {category} {page} en query o ruta; get usa {id} en la ruta. responsePath = donde esta la lista / el producto.',
  '  db: { search: { sql }, get: { sql }, fields, currency }. UN SELECT de solo lectura, sin comentarios, con :q y',
  '    :category (search) y :id (get); el modelo nunca escribe SQL. agent-master pagina (20 filas) y pone el tiempo limite.',
  '  fields: { id, title, price, currency, sku, stock, description, category, imageUrl, status } = ruta en el JSON o columna',
  '    (id y title obligatorios). currency por omision MXN. revisar_borrador avisa si algo no cuadra.',
  '  create_quote solo cotiza productos del hub: con una fuente http o db el bot ofrece que una persona cotice.',
  '',
  'Como trabajar:',
  '1. listar_agentes -> ver_borrador. Nunca cambies algo sin leerlo primero.',
  '2. cambiar_borrador con la forma de ver_borrador. Una lista (phases, transitions, bindings, extras.*) se reemplaza',
  '   entera: manda la lista completa ya editada. settings solo cambia los campos que mandes.',
  '3. revisar_borrador: corrige cada issue antes de publicar. changed dice que vera distinto el lead.',
  '4. Explica en palabras simples que cambia, pide confirmacion y entonces publicar_agente con confirmado=true y una nota.',
  '   Guardar el borrador NO cambia al agente: hasta publicar_agente nada llega a los leads. Si hay warnings, dilos.',
  '5. Si algo salio mal: historial_publicaciones y restaurar_revision (tambien con confirmacion).',
  '',
  'Reglas:',
  '- Editar el borrador no afecta a nadie; publicar SI (agent-master lo usa en segundos).',
  '- Nunca pongas llaves, tokens ni contrasenas en la configuracion: el hub lo rechaza; van en una conexion',
  '  (guardar_conexion; el secreto se cifra y nunca se vuelve a ver). Un servidor MCP que pide llave: guardar_conexion',
  '  (tipo mcp, config header) -> guardar_servidor_mcp con conexion = ese nombre -> publicar.',
  '- Herramientas MCP: ANTES de escribir toolAllowList o requiredTools usa listar_herramientas_servidor_mcp y copia los nombres',
  '  exactos (nunca los adivines). revisar_borrador y publicar bloquean un nombre que el servidor no tiene y te dicen los reales.',
  '- Herramientas HTTP propias (un API de la cuenta): guardar_herramienta_http -> agregar su clave a phases[].tools de la fase',
  '  -> publicar. POST/PUT/PATCH mandan como JSON los parametros que no van en la url ni en query. La llave del API va en una',
  '  conexion (guardar_conexion, tipo http, config header), nunca en headers.',
  '- La fase solo ofrece las de su toolAllowList (vacia = ninguna). El modelo las ve, y las trazas las',
  '  guardan, como mcp_<servidor>__<herramienta> (servidor en minusculas, sin espacios): usa ESE nombre en',
  '  transitions[].requires.toolsCalled. requiredTools usa el nombre simple de la herramienta.',
  '- Un numero solo puede atenderlo un agente: si ya es de otro, el hub responde 409.',
  '- Si la persona tiene varias cuentas, pregunta con cual trabajar (listar_cuentas / elegir_cuenta).',
].join('\n');

export const registrarGuia = (server) => {
  server.registerResource(
    'guia-agentes',
    'guia://agentes',
    { title: 'Guia de agentes', description: 'Como esta armado un agente y como editarlo y publicarlo sin riesgos.', mimeType: 'text/markdown' },
    async (uri) => ({ contents: [{ uri: uri.href, mimeType: 'text/markdown', text: GUIA }] }),
  );
  server.registerPrompt(
    'configurar_agente',
    {
      title: 'Configurar un agente',
      description: 'Revisa un agente y te ayuda a cambiar como contesta, paso a paso y con confirmacion antes de publicar.',
      argsSchema: {},
    },
    () => ({
      messages: [{
        role: 'user',
        content: {
          type: 'text',
          text: [
            'Quiero revisar y ajustar uno de mis agentes del hub.',
            '',
            '1. Si tengo varias cuentas, preguntame con cual (listar_cuentas / elegir_cuenta).',
            '2. Lista mis agentes y preguntame cual. Lee su borrador y resumeme en espanol simple como contesta hoy:',
            '   persona, reglas, fases con su objetivo, y que numero atiende.',
            '3. Preguntame que quiero cambiar. Haz el cambio en el borrador y corre revisar_borrador.',
            '4. NO publiques sin que yo lo confirme: dime antes que cambia para el lead.',
          ].join('\n'),
        },
      }],
    }),
  );
};
